public class PrimitiveData
{
    public static void main(String[]args)
    {
        byte age = 20;
        short year = 2026;
        int salary = 10000;
        long population = 2000000000l;

        float percentage = 98.9f;
        double pi = 3.45234423;

        char grade = 'B';
        boolean isPassed = false;

        System.out.println("Byte: " + age);
        System.out.println("Short: " + year);
        System.out.println("Int : " + salary);
        System.out.println("Long: " + population);
        System.out.println("Float: " + percentage);
        System.out.println("Double: " + pi);
        System.out.println("Char: " + grade);
        System.out.println("Boolean: " + isPassed);
    }
}
